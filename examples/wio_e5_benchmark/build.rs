fn main() {
    let out = &PathBuf::from(env::var_os("OUT_DIR").unwrap());
    File::create(out.join("memory.x"))
        .unwrap()
        .write_all(include_bytes!("memory.x"))
        .unwrap();
    File::create(out.join("lut_generated.rs"))
        .unwrap()
        .write_all(generate_lut_benchmark().as_bytes())
        .unwrap();
    File::create(out.join("lut_shd_model.rs"))
        .unwrap()
        .write_all(generate_lut_shd_model().as_bytes())
        .unwrap();
    File::create(out.join("lut_deps.rs"))
        .unwrap()
        .write_all(generate_lut_dependencies().as_bytes())
        .unwrap();
    File::create(out.join("bp_shd_model.rs"))
        .unwrap()
        .write_all(generate_bp_shd_model().as_bytes())
        .unwrap();
    File::create(out.join("tree_shd_model.rs"))
        .unwrap()
        .write_all(generate_tree_shd_model().as_bytes())
        .unwrap();
    File::create(out.join("cnn_shd_model.rs"))
        .unwrap()
        .write_all(generate_cnn_shd_model().as_bytes())
        .unwrap();
    build_cmsis_nn(out);
    File::create(out.join("bnn_shd_model.rs"))
        .unwrap()
        .write_all(generate_bnn_shd_model().as_bytes())
        .unwrap();
    println!("cargo:rustc-link-search={}", out.display());
    println!("cargo:rerun-if-changed=memory.x");
    println!("cargo:rerun-if-changed=build.rs");
    for var in [
        "CMSIS_AR",
        "LUT_MODEL_DIR",
        "BNN_MODEL_DIR",
        "SHD_CHUNK_START",
        "SHD_CHUNK_LEN",
        "LUT_HOST_PRED",
        "LUT_EE_DELTA",
        "BP_MODEL_DIR",
        "TREE_MODEL_DIR",
        "CNN_MODEL_DIR",
        "CMSIS_NN_DIR",
        "CMSIS_CORE_DIR",
    ] {
        println!("cargo:rerun-if-env-changed={var}");
    }
}

/// Deterministic 64-bit LCG (Knuth MMIX constants), so the generated benchmark never changes.
struct Lcg(u64);

impl Lcg {
    fn next(&mut self) -> u64 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        self.0 >> 11
    }

    fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
}

// Shape of the LUT micro-benchmark (synthetic connections and tables).
const WORDS: u64 = 128; // 4,096 history bits = 64 channels x 64 ticks, as u32 words
const GROUPS: usize = 20; // one group per SHD class
const K6_LUTS: usize = 256;
const K8_LUTS: usize = 64;

/// Generates the code of `bin/lut_benchmark.rs`: random bit addresses and tables, the same
/// layer as data (`LUT6_ADDR`, `LUT6_TABLE`) and as straight-line code with constant bit
/// positions (`lut6_layer_codegen`), and a k = 8 variant with int8 table entries.
fn generate_lut_benchmark() -> String {
    let mut rng = Lcg(0x5EED_1234_ABCD_0042);
    let mut s = String::new();
    writeln!(s, "// Generated by build.rs; do not edit.").unwrap();
    writeln!(s, "pub const LUT_WORDS: usize = {WORDS};").unwrap();
    writeln!(s, "pub const LUT_GROUPS: usize = {GROUPS};").unwrap();
    writeln!(s, "pub const LUT6_N: usize = {K6_LUTS};").unwrap();
    writeln!(s, "pub const LUT8_N: usize = {K8_LUTS};").unwrap();

    // k = 6, 1-bit outputs, group-sum readout.
    let addr6: Vec<[(u64, u64); 6]> = (0..K6_LUTS)
        .map(|_| core::array::from_fn(|_| (rng.below(WORDS), rng.below(32))))
        .collect();
    let table6: Vec<u64> = (0..K6_LUTS).map(|_| rng.next() ^ (rng.next() << 21)).collect();

    writeln!(s, "pub static LUT6_ADDR: [[[u8; 2]; 6]; LUT6_N] = [").unwrap();
    for a in &addr6 {
        let pairs: Vec<String> = a.iter().map(|(w, b)| format!("[{w}, {b}]")).collect();
        writeln!(s, "    [{}],", pairs.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s, "pub static LUT6_TABLE: [u64; LUT6_N] = [").unwrap();
    for t in &table6 {
        writeln!(s, "    0x{t:016X},").unwrap();
    }
    writeln!(s, "];").unwrap();

    writeln!(s, "#[inline(never)]").unwrap();
    writeln!(
        s,
        "pub fn lut6_layer_codegen(w: &[u32; LUT_WORDS], counts: &mut [u16; LUT_GROUPS]) {{"
    )
    .unwrap();
    for (n, (a, t)) in addr6.iter().zip(&table6).enumerate() {
        let bits: Vec<String> = a
            .iter()
            .enumerate()
            .map(|(i, (word, bit))| format!("(((w[{word}] >> {bit}) & 1) << {i})"))
            .collect();
        writeln!(s, "    let i = {};", bits.join(" | ")).unwrap();
        writeln!(
            s,
            "    counts[{}] += ((0x{t:016X}u64 >> i) & 1) as u16;",
            n % GROUPS
        )
        .unwrap();
    }
    writeln!(s, "}}").unwrap();

    // k = 8, int8 outputs read with LDRB, summed into int32 class scores.
    let addr8: Vec<[(u64, u64); 8]> = (0..K8_LUTS)
        .map(|_| core::array::from_fn(|_| (rng.below(WORDS), rng.below(32))))
        .collect();
    writeln!(s, "pub static LUT8_TABLE: [[i8; 256]; LUT8_N] = [").unwrap();
    for _ in 0..K8_LUTS {
        let row: Vec<String> = (0..256).map(|_| ((rng.next() % 255) as i64 - 127).to_string()).collect();
        writeln!(s, "    [{}],", row.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s, "#[inline(never)]").unwrap();
    writeln!(
        s,
        "pub fn lut8_layer_codegen(w: &[u32; LUT_WORDS], scores: &mut [i32; LUT_GROUPS]) {{"
    )
    .unwrap();
    for (n, a) in addr8.iter().enumerate() {
        let bits: Vec<String> = a
            .iter()
            .enumerate()
            .map(|(i, (word, bit))| format!("(((w[{word}] >> {bit}) & 1) << {i})"))
            .collect();
        writeln!(s, "    let i = ({}) as usize;", bits.join(" | ")).unwrap();
        writeln!(
            s,
            "    scores[{}] += i32::from(LUT8_TABLE[{n}][i]);",
            n % GROUPS
        )
        .unwrap();
    }
    writeln!(s, "}}").unwrap();
    s
}

/// Embeds a trained LUT network and one chunk of the packed SHD test set for `bin/lut_shd_eval.rs`.
///
/// Reads the files written by `tools/bptn_torch/train_shd_comparison.py --export-lut DIR` from
/// `LUT_MODEL_DIR`, and samples `[SHD_CHUNK_START, SHD_CHUNK_START + SHD_CHUNK_LEN)` of the test
/// set. Without `LUT_MODEL_DIR` it emits an empty model, so the crate still builds.
fn generate_lut_shd_model() -> String {
    let mut s = String::from("// Generated by build.rs from LUT_MODEL_DIR; do not edit.\n");
    let Some(dir) = env::var_os("LUT_MODEL_DIR").map(PathBuf::from) else {
        s.push_str("pub const MODEL_PRESENT: bool = false;\npub const N_LUTS: usize = 20;\n");
        s.push_str("pub const EE_DELTA: u32 = 0;\n");
        // Two words = one channel, so the streaming binary still has a non-empty channel loop.
        s.push_str("pub const WORDS: usize = 2;\npub const CHUNK_START: usize = 0;\n");
        s.push_str("pub static LUT_ADDR: [[[u8; 2]; 6]; N_LUTS] = [[[0; 2]; 6]; N_LUTS];\n");
        s.push_str("pub static LUT_TABLE: [u64; N_LUTS] = [0; N_LUTS];\n");
        s.push_str("pub static TEST_X: [[u32; WORDS]; 0] = [];\npub static TEST_Y: [u8; 0] = [];\n");
        s.push_str("pub static HOST_PRED: [u8; 0] = [];\n");
        return s;
    };
    let read = |name: &str| read_export(&dir, name);
    let addr = read("lut_addr.bin");
    let table = read("lut_table.bin");
    let x = read("test_x.bin");
    let y = read("test_y.bin");
    // Expected predictions: the full evaluation, or the early-exit rule (`LUT_HOST_PRED`).
    let host = read(&env::var("LUT_HOST_PRED").unwrap_or_else(|_| "host_pred.bin".into()));
    // Early-exit margin for `lut_shd_early_exit` (0 = exact rule).
    let ee_delta: u32 = env::var("LUT_EE_DELTA").map_or(0, |v| v.parse().unwrap());

    let n_luts = table.len() / 8;
    assert_eq!(addr.len(), n_luts * 12, "lut_addr.bin must hold 6 (word, bit) pairs per LUT");
    let (start, end, words) = chunk_bounds(&x, &y);

    writeln!(s, "pub const MODEL_PRESENT: bool = true;").unwrap();
    writeln!(s, "pub const N_LUTS: usize = {n_luts};").unwrap();
    writeln!(s, "pub const EE_DELTA: u32 = {ee_delta};").unwrap();
    writeln!(s, "pub const WORDS: usize = {words};").unwrap();
    writeln!(s, "pub const CHUNK_START: usize = {start};").unwrap();
    writeln!(s, "pub static LUT_ADDR: [[[u8; 2]; 6]; N_LUTS] = [").unwrap();
    for lut in addr.chunks(12) {
        let pairs: Vec<String> = lut.chunks(2).map(|p| format!("[{}, {}]", p[0], p[1])).collect();
        writeln!(s, "    [{}],", pairs.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s, "pub static LUT_TABLE: [u64; N_LUTS] = [").unwrap();
    for t in table.chunks(8) {
        writeln!(s, "    0x{:016X},", u64::from_le_bytes(t.try_into().unwrap())).unwrap();
    }
    writeln!(s, "];").unwrap();
    write_test_chunk(&mut s, &x, &y, &host, start, end, words);
    s
}

fn read_export(dir: &std::path::Path, name: &str) -> Vec<u8> {
    let path = dir.join(name);
    println!("cargo:rerun-if-changed={}", path.display());
    std::fs::read(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()))
}

/// `[start, end)` sample range of the chunk selected by `SHD_CHUNK_START` / `SHD_CHUNK_LEN`, and
/// the number of u32 words per sample.
fn chunk_bounds(x: &[u8], y: &[u8]) -> (usize, usize, usize) {
    let samples = y.len();
    let words = x.len() / 4 / samples;
    let start: usize = env::var("SHD_CHUNK_START").map_or(0, |v| v.parse().unwrap());
    let len: usize = env::var("SHD_CHUNK_LEN").map_or(samples, |v| v.parse().unwrap());
    (start, (start + len).min(samples), words)
}

fn write_test_chunk(s: &mut String, x: &[u8], y: &[u8], host: &[u8], start: usize, end: usize, words: usize) {
    writeln!(s, "pub static TEST_X: [[u32; WORDS]; {}] = [", end - start).unwrap();
    for i in start..end {
        let row: Vec<String> = x[i * words * 4..(i + 1) * words * 4]
            .chunks(4)
            .map(|b| format!("0x{:08X}", u32::from_le_bytes(b.try_into().unwrap())))
            .collect();
        writeln!(s, "    [{}],", row.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s, "pub static TEST_Y: [u8; {}] = {:?};", end - start, &y[start..end]).unwrap();
    writeln!(s, "pub static HOST_PRED: [u8; {}] = {:?};", end - start, &host[start..end]).unwrap();
}

/// Embeds a trained binarized network (from `--export-bnn DIR`, read from `BNN_MODEL_DIR`) and one
/// chunk of the packed SHD test set for `bin/bnn_shd_eval.rs`.
fn generate_bnn_shd_model() -> String {
    let mut s = String::from("// Generated by build.rs from BNN_MODEL_DIR; do not edit.\n");
    let Some(dir) = env::var_os("BNN_MODEL_DIR").map(PathBuf::from) else {
        s.push_str("pub const MODEL_PRESENT: bool = false;\npub const HIDDEN: usize = 1;\n");
        s.push_str("pub const WORDS: usize = 1;\npub const CHUNK_START: usize = 0;\n");
        s.push_str("pub static BNN_WEIGHTS: [[u32; WORDS]; HIDDEN] = [[0; WORDS]; HIDDEN];\n");
        s.push_str("pub static BNN_MAX_MISMATCH: [i32; HIDDEN] = [0; HIDDEN];\n");
        s.push_str("pub static READOUT_W: [[i8; HIDDEN]; 20] = [[0; HIDDEN]; 20];\n");
        s.push_str("pub static READOUT_B: [i32; 20] = [0; 20];\n");
        s.push_str("pub static TEST_X: [[u32; WORDS]; 0] = [];\npub static TEST_Y: [u8; 0] = [];\n");
        s.push_str("pub static HOST_PRED: [u8; 0] = [];\n");
        return s;
    };
    let weights = read_export(&dir, "bnn_weights.bin");
    let max_mismatch = read_export(&dir, "bnn_max_mismatch.bin");
    let rw = read_export(&dir, "readout_w.bin");
    let rb = read_export(&dir, "readout_b.bin");
    let x = read_export(&dir, "test_x.bin");
    let y = read_export(&dir, "test_y.bin");
    let host = read_export(&dir, "host_pred.bin");

    let hidden = max_mismatch.len() / 4;
    let (start, end, words) = chunk_bounds(&x, &y);
    assert_eq!(weights.len(), hidden * words * 4, "bnn_weights.bin size");
    assert_eq!(rw.len(), 20 * hidden, "readout_w.bin size");

    let i32s = |b: &[u8]| -> Vec<String> {
        b.chunks(4).map(|c| i32::from_le_bytes(c.try_into().unwrap()).to_string()).collect()
    };
    writeln!(s, "pub const MODEL_PRESENT: bool = true;").unwrap();
    writeln!(s, "pub const HIDDEN: usize = {hidden};").unwrap();
    writeln!(s, "pub const WORDS: usize = {words};").unwrap();
    writeln!(s, "pub const CHUNK_START: usize = {start};").unwrap();
    writeln!(s, "pub static BNN_WEIGHTS: [[u32; WORDS]; HIDDEN] = [").unwrap();
    for row in weights.chunks(words * 4) {
        let r: Vec<String> = row
            .chunks(4)
            .map(|b| format!("0x{:08X}", u32::from_le_bytes(b.try_into().unwrap())))
            .collect();
        writeln!(s, "    [{}],", r.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s, "pub static BNN_MAX_MISMATCH: [i32; HIDDEN] = [{}];", i32s(&max_mismatch).join(", ")).unwrap();
    writeln!(s, "pub static READOUT_W: [[i8; HIDDEN]; 20] = [").unwrap();
    for row in rw.chunks(hidden) {
        let r: Vec<String> = row.iter().map(|&b| (b as i8).to_string()).collect();
        writeln!(s, "    [{}],", r.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s, "pub static READOUT_B: [i32; 20] = [{}];", i32s(&rb).join(", ")).unwrap();
    write_test_chunk(&mut s, &x, &y, &host, start, end, words);
    s
}

/// For `bin/lut_stream_eval.rs`: for each input position, the LUTs that read it (CSR layout:
/// `DEP_PTR[f]..DEP_PTR[f + 1]` indexes `DEP_LUT`). Empty without `LUT_MODEL_DIR`.
fn generate_lut_dependencies() -> String {
    let mut s = String::from("// Generated by build.rs from LUT_MODEL_DIR; do not edit.\n");
    let Some(dir) = env::var_os("LUT_MODEL_DIR").map(PathBuf::from) else {
        s.push_str("pub static DEP_PTR: [u16; 2] = [0, 0];\npub static DEP_LUT: [u16; 0] = [];\n");
        return s;
    };
    let addr = read_export(&dir, "lut_addr.bin");
    let x = read_export(&dir, "test_x.bin");
    let y = read_export(&dir, "test_y.bin");
    let positions = x.len() / y.len() * 8; // bits per sample
    let mut deps: Vec<Vec<u16>> = vec![Vec::new(); positions];
    for (n, lut) in addr.chunks(12).enumerate() {
        for p in lut.chunks(2) {
            deps[usize::from(p[0]) * 32 + usize::from(p[1])].push(n as u16);
        }
    }
    let mut ptr = vec![0u16];
    let mut flat = Vec::new();
    for d in &deps {
        flat.extend_from_slice(d);
        ptr.push(flat.len() as u16);
    }
    writeln!(s, "pub static DEP_PTR: [u16; {}] = {:?};", ptr.len(), ptr).unwrap();
    writeln!(s, "pub static DEP_LUT: [u16; {}] = {:?};", flat.len(), flat).unwrap();
    s
}

/// Embeds a trained forest of LUT decision trees (from `--export-bp DIR`, read from
/// `BP_MODEL_DIR`) and one chunk of the packed SHD test set for `bin/bp_shd_eval.rs`.
fn generate_bp_shd_model() -> String {
    let mut s = String::from("// Generated by build.rs from BP_MODEL_DIR; do not edit.\n");
    let Some(dir) = env::var_os("BP_MODEL_DIR").map(PathBuf::from) else {
        s.push_str("pub const MODEL_PRESENT: bool = false;\npub const TREES: usize = 1;\n");
        s.push_str("pub const DEPTH: usize = 1;\npub const WORDS: usize = 2;\npub const CHUNK_START: usize = 0;\n");
        s.push_str("pub static BP_ADDR: [[[u8; 2]; 6]; 1] = [[[0; 2]; 6]];\n");
        s.push_str("pub static BP_TABLE: [u64; 1] = [0];\npub static BP_LEAF: [[i8; 20]; 2] = [[0; 20]; 2];\n");
        s.push_str("pub static TEST_X: [[u32; WORDS]; 0] = [];\npub static TEST_Y: [u8; 0] = [];\n");
        s.push_str("pub static HOST_PRED: [u8; 0] = [];\n");
        return s;
    };
    let meta = String::from_utf8(read_export(&dir, "meta.json")).unwrap();
    let field = |name: &str| -> usize {
        let key = format!("\"{name}\": ");
        let start = meta.find(&key).unwrap_or_else(|| panic!("meta.json has no {name}")) + key.len();
        meta[start..].chars().take_while(char::is_ascii_digit).collect::<String>().parse().unwrap()
    };
    let (trees, depth) = (field("trees"), field("depth"));
    let addr = read_export(&dir, "bp_addr.bin");
    let table = read_export(&dir, "bp_table.bin");
    let leaf = read_export(&dir, "bp_leaf.bin");
    let x = read_export(&dir, "test_x.bin");
    let y = read_export(&dir, "test_y.bin");
    let host = read_export(&dir, "host_pred.bin");
    let nodes = trees * ((1 << depth) - 1);
    let leaves = trees << depth;
    assert_eq!(table.len(), nodes * 8, "bp_table.bin size");
    assert_eq!(addr.len(), nodes * 12, "bp_addr.bin size (k = 6)");
    assert_eq!(leaf.len(), leaves * 20, "bp_leaf.bin size");
    let (start, end, words) = chunk_bounds(&x, &y);

    writeln!(s, "pub const MODEL_PRESENT: bool = true;").unwrap();
    writeln!(s, "pub const TREES: usize = {trees};").unwrap();
    writeln!(s, "pub const DEPTH: usize = {depth};").unwrap();
    writeln!(s, "pub const WORDS: usize = {words};").unwrap();
    writeln!(s, "pub const CHUNK_START: usize = {start};").unwrap();
    writeln!(s, "pub static BP_ADDR: [[[u8; 2]; 6]; {nodes}] = [").unwrap();
    for node in addr.chunks(12) {
        let pairs: Vec<String> = node.chunks(2).map(|p| format!("[{}, {}]", p[0], p[1])).collect();
        writeln!(s, "    [{}],", pairs.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s, "pub static BP_TABLE: [u64; {nodes}] = [").unwrap();
    for t in table.chunks(8) {
        writeln!(s, "    0x{:016X},", u64::from_le_bytes(t.try_into().unwrap())).unwrap();
    }
    writeln!(s, "];").unwrap();
    writeln!(s, "pub static BP_LEAF: [[i8; 20]; {leaves}] = [").unwrap();
    for l in leaf.chunks(20) {
        let r: Vec<String> = l.iter().map(|&b| (b as i8).to_string()).collect();
        writeln!(s, "    [{}],", r.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    write_test_chunk(&mut s, &x, &y, &host, start, end, words);
    s
}

/// Embeds a classic tree ensemble (random forest or gradient boosting, from
/// `tools/bptn_torch/tree_baselines.py --export DIR`, read from `TREE_MODEL_DIR`) and one chunk of
/// the packed SHD test set for `bin/tree_shd_eval.rs`.
fn generate_tree_shd_model() -> String {
    let mut s = String::from("// Generated by build.rs from TREE_MODEL_DIR; do not edit.\n");
    let Some(dir) = env::var_os("TREE_MODEL_DIR").map(PathBuf::from) else {
        s.push_str("pub const MODEL_PRESENT: bool = false;\npub const LEAF_VECTOR: bool = true;\n");
        s.push_str("pub const WORDS: usize = 2;\npub const CHUNK_START: usize = 0;\n");
        s.push_str("pub static TREE_NODES: [[u16; 3]; 1] = [[0, 0x8000, 0x8000]];\n");
        s.push_str("pub static TREE_ROOTS: [u16; 1] = [0x8000];\npub static TREE_CLASS: [u8; 1] = [0];\n");
        s.push_str("pub static LEAF_VEC: [[i8; 20]; 1] = [[0; 20]];\npub static LEAF_VAL: [i16; 0] = [];\n");
        s.push_str("pub static TREE_BASE: [i32; 20] = [0; 20];\n");
        s.push_str("pub static TEST_X: [[u32; WORDS]; 0] = [];\npub static TEST_Y: [u8; 0] = [];\n");
        s.push_str("pub static HOST_PRED: [u8; 0] = [];\n");
        return s;
    };
    let meta = String::from_utf8(read_export(&dir, "meta.json")).unwrap();
    let vector = meta.contains("\"vector_i8\"");
    let nodes = read_export(&dir, "tree_nodes.bin");
    let roots = read_export(&dir, "tree_roots.bin");
    let class = read_export(&dir, "tree_class.bin");
    let leaves = read_export(&dir, "tree_leaves.bin");
    let base = read_export(&dir, "tree_base.bin");
    let x = read_export(&dir, "test_x.bin");
    let y = read_export(&dir, "test_y.bin");
    let host = read_export(&dir, "host_pred.bin");
    let (start, end, words) = chunk_bounds(&x, &y);
    let u16s = |b: &[u8]| -> Vec<u16> { b.chunks(2).map(|c| u16::from_le_bytes(c.try_into().unwrap())).collect() };

    writeln!(s, "pub const MODEL_PRESENT: bool = true;").unwrap();
    writeln!(s, "pub const LEAF_VECTOR: bool = {vector};").unwrap();
    writeln!(s, "pub const WORDS: usize = {words};").unwrap();
    writeln!(s, "pub const CHUNK_START: usize = {start};").unwrap();
    let n = u16s(&nodes);
    writeln!(s, "pub static TREE_NODES: [[u16; 3]; {}] = [", n.len() / 3).unwrap();
    for node in n.chunks(3) {
        writeln!(s, "    [{}, {}, {}],", node[0], node[1], node[2]).unwrap();
    }
    writeln!(s, "];").unwrap();
    let r = u16s(&roots);
    writeln!(s, "pub static TREE_ROOTS: [u16; {}] = {:?};", r.len(), r).unwrap();
    writeln!(s, "pub static TREE_CLASS: [u8; {}] = {:?};", class.len(), class).unwrap();
    if vector {
        writeln!(s, "pub static LEAF_VEC: [[i8; 20]; {}] = [", leaves.len() / 20).unwrap();
        for l in leaves.chunks(20) {
            let v: Vec<String> = l.iter().map(|&b| (b as i8).to_string()).collect();
            writeln!(s, "    [{}],", v.join(", ")).unwrap();
        }
        writeln!(s, "];\npub static LEAF_VAL: [i16; 0] = [];").unwrap();
    } else {
        let v: Vec<i16> = leaves.chunks(2).map(|c| i16::from_le_bytes(c.try_into().unwrap())).collect();
        writeln!(s, "pub static LEAF_VEC: [[i8; 20]; 0] = [];").unwrap();
        writeln!(s, "pub static LEAF_VAL: [i16; {}] = {:?};", v.len(), v).unwrap();
    }
    let b: Vec<i32> = base.chunks(4).map(|c| i32::from_le_bytes(c.try_into().unwrap())).collect();
    writeln!(s, "pub static TREE_BASE: [i32; 20] = {:?};", b).unwrap();
    write_test_chunk(&mut s, &x, &y, &host, start, end, words);
    s
}

/// Compiles the s8 CMSIS-NN kernels with clang for the Cortex-M4 when `CMSIS_NN_DIR` (the CMSIS-NN
/// repository) and `CMSIS_CORE_DIR` (`CMSIS/Core/Include` of CMSIS_6) are set, and enables
/// `cfg(cmsis_nn)`; `CMSIS_AR` selects the archiver. A minimal `string.h` is provided: the freestanding target has no C library,
/// and `memcpy` / `memset` / `memmove` come from Rust's compiler builtins at link time.
fn build_cmsis_nn(out: &std::path::Path) {
    println!("cargo:rustc-check-cfg=cfg(cmsis_nn)");
    let (Some(nn), Some(core)) = (env::var_os("CMSIS_NN_DIR"), env::var_os("CMSIS_CORE_DIR")) else {
        return;
    };
    let nn = PathBuf::from(nn);
    let shim = out.join("cmsis_shim");
    std::fs::create_dir_all(&shim).unwrap();
    std::fs::write(
        shim.join("string.h"),
        "#pragma once\n#include <stddef.h>\n\
         void *memcpy(void *, const void *, size_t);\n\
         void *memmove(void *, const void *, size_t);\n\
         void *memset(void *, int, size_t);\n",
    )
    .unwrap();
    let mut build = cc::Build::new();
    build
        .compiler("clang")
        .flag("--target=thumbv7em-none-eabi")
        .flag("-mcpu=cortex-m4")
        .flag("-mthumb")
        .flag("-mfloat-abi=soft")
        .flag("-ffreestanding")
        .flag("-fno-builtin")
        .opt_level(3)
        .include(&shim)
        .include(nn.join("Include"))
        .include(PathBuf::from(core))
        .warnings(false);
    // The int8 kernels used by cnn_shd_eval (convolution, average pooling, fully connected) and the
    // support functions they call.
    for dir in ["ConvolutionFunctions", "FullyConnectedFunctions", "PoolingFunctions", "NNSupportFunctions"] {
        let path = nn.join("Source").join(dir);
        println!("cargo:rerun-if-changed={}", path.display());
        for entry in std::fs::read_dir(&path).unwrap() {
            let file = entry.unwrap().path();
            let name = file.file_name().unwrap().to_string_lossy().into_owned();
            let int8 = name.contains("_s8") || name.contains("_q7") || name.starts_with("arm_nn_");
            let float = name.contains("f16") || name.contains("f32");
            if name.ends_with(".c") && int8 && !float {
                build.file(&file);
            }
        }
    }
    // The host `ar` / `ranlib` of macOS cannot index ELF objects, so the archive is built with an
    // LLVM archiver (`CMSIS_AR`, default `rust-ar` from cargo-binutils); `s` writes the symbol index.
    let objects = build.compile_intermediates();
    let archive = out.join("libcmsis_nn.a");
    let _ = std::fs::remove_file(&archive);
    let ar = env::var("CMSIS_AR").unwrap_or_else(|_| "rust-ar".into());
    let status = std::process::Command::new(&ar)
        .arg("crs")
        .arg(&archive)
        .args(&objects)
        .status()
        .unwrap_or_else(|e| panic!("cannot run {ar}: {e}"));
    assert!(status.success(), "{ar} failed");
    println!("cargo:rustc-link-search=native={}", out.display());
    println!("cargo:rustc-link-lib=static=cmsis_nn");
    println!("cargo:rustc-cfg=cmsis_nn");
}

/// Embeds a quantized CNN (from `tools/bptn_torch/cnn_int8_baseline.py --export-dir`, read from
/// `CNN_MODEL_DIR`) and one chunk of the packed SHD test set for `bin/cnn_shd_eval.rs`.
fn generate_cnn_shd_model() -> String {
    let mut s = String::from("// Generated by build.rs from CNN_MODEL_DIR; do not edit.\n");
    let Some(dir) = env::var_os("CNN_MODEL_DIR").map(PathBuf::from) else {
        s.push_str("pub const MODEL_PRESENT: bool = false;\n");
        s.push_str("pub const C1: usize = 1;\npub const K1: usize = 1;\npub const S1: usize = 1;\n");
        s.push_str("pub const C2: usize = 1;\npub const K2: usize = 1;\npub const S2: usize = 1;\n");
        s.push_str("pub const W1: usize = 1;\npub const W2: usize = 1;\n");
        s.push_str("pub const FC_MULT: i32 = 0;\npub const FC_SHIFT: i32 = 0;\n");
        s.push_str("pub static CONV1_W: [i8; 64] = [0; 64];\npub static CONV1_B: [i32; 1] = [0];\n");
        s.push_str("pub static CONV1_MULT: [i32; 1] = [0];\npub static CONV1_SHIFT: [i32; 1] = [0];\n");
        s.push_str("pub static CONV2_W: [i8; 1] = [0];\npub static CONV2_B: [i32; 1] = [0];\n");
        s.push_str("pub static CONV2_MULT: [i32; 1] = [0];\npub static CONV2_SHIFT: [i32; 1] = [0];\n");
        s.push_str("pub static FC_W: [i8; 20] = [0; 20];\npub static FC_B: [i32; 20] = [0; 20];\n");
        s.push_str("pub const WORDS: usize = 128;\npub const CHUNK_START: usize = 0;\n");
        s.push_str("pub static TEST_X: [[u32; WORDS]; 0] = [];\npub static TEST_Y: [u8; 0] = [];\n");
        s.push_str("pub static HOST_PRED: [u8; 0] = [];\n");
        return s;
    };
    let meta = String::from_utf8(read_export(&dir, "meta.json")).unwrap();
    let field = |name: &str| -> i64 {
        let key = format!("\"{name}\": ");
        let start = meta.find(&key).unwrap_or_else(|| panic!("meta.json has no {name}")) + key.len();
        meta[start..]
            .chars()
            .take_while(|c| c.is_ascii_digit() || *c == '-')
            .collect::<String>()
            .parse()
            .unwrap()
    };
    let (c1, k1, s1, c2, k2, s2) =
        (field("c1"), field("k1"), field("s1"), field("c2"), field("k2"), field("s2"));
    let w1 = (64 - k1) / s1 + 1;
    let w2 = (w1 - k2) / s2 + 1;
    for (name, v) in [("C1", c1), ("K1", k1), ("S1", s1), ("C2", c2), ("K2", k2), ("S2", s2), ("W1", w1), ("W2", w2)] {
        writeln!(s, "pub const {name}: usize = {v};").unwrap();
    }
    writeln!(s, "pub const MODEL_PRESENT: bool = true;").unwrap();
    writeln!(s, "pub const FC_MULT: i32 = {};", field("fc_mult")).unwrap();
    writeln!(s, "pub const FC_SHIFT: i32 = {};", field("fc_shift")).unwrap();
    let i8s = |name: &str| -> Vec<i8> { read_export(&dir, name).iter().map(|&b| b as i8).collect() };
    let i32s = |name: &str| -> Vec<i32> {
        read_export(&dir, name).chunks(4).map(|c| i32::from_le_bytes(c.try_into().unwrap())).collect()
    };
    for (name, file) in [("CONV1_W", "conv1_w.bin"), ("CONV2_W", "conv2_w.bin"), ("FC_W", "fc_w.bin")] {
        let v = i8s(file);
        writeln!(s, "pub static {name}: [i8; {}] = {:?};", v.len(), v).unwrap();
    }
    for (name, file) in [
        ("CONV1_B", "conv1_b.bin"),
        ("CONV1_MULT", "conv1_mult.bin"),
        ("CONV1_SHIFT", "conv1_shift.bin"),
        ("CONV2_B", "conv2_b.bin"),
        ("CONV2_MULT", "conv2_mult.bin"),
        ("CONV2_SHIFT", "conv2_shift.bin"),
        ("FC_B", "fc_b.bin"),
    ] {
        let v = i32s(file);
        writeln!(s, "pub static {name}: [i32; {}] = {:?};", v.len(), v).unwrap();
    }
    let x = read_export(&dir, "test_x.bin");
    let y = read_export(&dir, "test_y.bin");
    let host = read_export(&dir, "host_pred.bin");
    let (start, end, words) = chunk_bounds(&x, &y);
    writeln!(s, "pub const WORDS: usize = {words};").unwrap();
    writeln!(s, "pub const CHUNK_START: usize = {start};").unwrap();
    write_test_chunk(&mut s, &x, &y, &host, start, end, words);
    s
}

