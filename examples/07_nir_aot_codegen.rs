//! 🌐 Example 7: AOT Deployment from Standardized NIR (Neuromorphic Intermediate Representation)
//!
//! Demonstrates the complete import pipeline from a PyTorch / snnTorch / Norse trained SNN
//! into 100% static embedded (`no_std`) Rust code:
//! 1. Ingestion of standardized NIR graph descriptors ([`NirAffineNode`], [`NirLifNode`]).
//! 2. Sparse CSR synaptic pruning and INT8 quantization.
//! 3. Static Rust Flash ROM (.rodata) code generation via [`emit_rust_static_csr`].
//! 4. Instantiation and real-time intra-tick inference via [`DeepSpikingNetwork2`].
//!
//! Execution:
//! ```bash
//! cargo run --example 07_nir_aot_codegen -p snn_core
//! ```

use snn_core::application::nir_import::{
    NirAffineNode, NirLifNode, NirLinearNode, emit_rust_static_csr,
};
use snn_core::domain::generic_static_neuron::GenericStaticNeuronPopulation;
use snn_core::domain::layers::{ChainedSpikingNetwork, SpikingFeedforwardLayer};
use snn_core::domain::models::lif::{LifDynamics, LifState};
use snn_core::domain::rom_csr::RomCsrSynapses;
use snn_core::{Fix32, LayerDescriptor, ModelDescriptor};

fn main() {
    println!("=== 🌐 snn_core: AOT Deployment from Standard NIR ===\n");

    // 1. Define synaptic weights for a 2-layer network trained in snnTorch (NIR format)
    // Layer 1: Inputs (4) -> Hidden (4)
    let layer1_weights_dense = [
        Fix32::from_num(1.2),
        Fix32::ZERO,
        Fix32::from_num(-0.5),
        Fix32::ZERO,
        Fix32::ZERO,
        Fix32::from_num(1.5),
        Fix32::ZERO,
        Fix32::from_num(-0.3),
        Fix32::from_num(0.8),
        Fix32::ZERO,
        Fix32::from_num(1.1),
        Fix32::ZERO,
        Fix32::ZERO,
        Fix32::from_num(-0.6),
        Fix32::ZERO,
        Fix32::from_num(1.4),
    ];
    let nir_layer1_linear = NirLinearNode::new(&layer1_weights_dense, 4, 4);
    let nir_layer1_affine = NirAffineNode::new(nir_layer1_linear, &[Fix32::ZERO; 4]);

    // Layer 2: Hidden (4) -> Output (2)
    let layer2_weights_dense = [
        Fix32::from_num(1.8),
        Fix32::ZERO,
        Fix32::from_num(1.2),
        Fix32::ZERO,
        Fix32::ZERO,
        Fix32::from_num(1.6),
        Fix32::ZERO,
        Fix32::from_num(1.9),
    ];
    let nir_layer2_linear = NirLinearNode::new(&layer2_weights_dense, 4, 2);

    // NIR neuron parameters: LIF with tau = 20ms, V_th = 1.0, dt = 1ms
    let nir_lif_node = NirLifNode {
        tau_mem: Fix32::from_num(20.0), // 20 ms
        v_threshold: Fix32::ONE,
        v_reset: Fix32::ZERO,
        r: Fix32::ONE,
    };
    let lif_config = nir_lif_node.to_lif_config(Fix32::ONE);
    println!("1. NIR biophysical parameters conversion (Padé (2,2) rational approximation):");
    println!(
        "   - Membrane decay factor (lambda): {:.6} (tau=20ms, dt=1ms)",
        lif_config.decay_factor.to_float()
    );
    println!(
        "   - Firing threshold (V_th)       : {:.2}",
        lif_config.threshold.to_float()
    );

    // 2. Static sparse CSR conversion (pruning near-zero weights / noise)
    let layer1_csr = nir_layer1_affine.to_static_csr::<5, 16>(Fix32::from_num(0.01));
    let layer2_csr = nir_layer2_linear.to_static_csr::<5, 8>(Fix32::from_num(0.01));

    println!("\n2. Sparse CSR synaptic compression:");
    println!(
        "   - Layer 1: {} active synapses out of 16 possible ({:.1}% sparsity)",
        layer1_csr.len(),
        100.0 * (1.0 - (layer1_csr.len() as f32 / 16.0))
    );
    println!(
        "   - Layer 2: {} active synapses out of 8 possible ({:.1}% sparsity)",
        layer2_csr.len(),
        100.0 * (1.0 - (layer2_csr.len() as f32 / 8.0))
    );

    // 3. AOT static source code generation for microcontrollers
    println!("\n3. Preview of AOT Rust code generated by `emit_rust_static_csr`:");
    let codegen_snippet = emit_rust_static_csr(
        "NIR_L1",
        &layer1_csr.row_ptrs,
        &layer1_csr.targets[..layer1_csr.len()],
        &layer1_csr.weights[..layer1_csr.len()],
    );
    for line in codegen_snippet.lines().take(3) {
        println!("   {}", line);
    }
    println!("   [...]\n");

    // 4. Instantiate 2-layer deep network (intra-tick Deep SNN)
    let l1_neurons =
        GenericStaticNeuronPopulation::<LifDynamics, 4>::new(lif_config, LifState::default());
    let l1_synapses = RomCsrSynapses::new(
        &layer1_csr.row_ptrs,
        &layer1_csr.targets[..layer1_csr.len()],
        &layer1_csr.weights[..layer1_csr.len()],
    );
    let layer1 = SpikingFeedforwardLayer::<_, _, 4, 1>::new(l1_neurons, l1_synapses);

    let l2_neurons =
        GenericStaticNeuronPopulation::<LifDynamics, 2>::new(lif_config, LifState::default());
    let l2_synapses = RomCsrSynapses::new(
        &layer2_csr.row_ptrs,
        &layer2_csr.targets[..layer2_csr.len()],
        &layer2_csr.weights[..layer2_csr.len()],
    );
    let layer2 = SpikingFeedforwardLayer::<_, _, 2, 1>::new(l2_neurons, l2_synapses);
    let mut deep_snn = ChainedSpikingNetwork::<_, 2>::new(snn_core::chain_layers!(layer1, layer2));

    // 5. Streaming inference test
    println!("4. Executing 5 time-steps (100% intra-tick direct feedforward):");
    let test_inputs = [
        [Fix32::from_num(1.5), Fix32::ZERO, Fix32::ZERO, Fix32::ZERO],
        [Fix32::from_num(1.5), Fix32::ZERO, Fix32::ZERO, Fix32::ZERO],
        [Fix32::ZERO, Fix32::from_num(1.8), Fix32::ZERO, Fix32::ZERO],
        [Fix32::ZERO, Fix32::ZERO, Fix32::ZERO, Fix32::from_num(2.0)],
        [Fix32::ZERO, Fix32::ZERO, Fix32::ZERO, Fix32::ZERO],
    ];

    for (t, inp) in test_inputs.iter().enumerate() {
        let out_spikes = deep_snn.tick(inp);
        println!(
            "   [Tick #{}] Active Inputs: {:?} -> Output Spikes: [Neuron 0: {}, Neuron 1: {}]",
            t,
            inp.iter().map(|v| v.to_float()).collect::<Vec<_>>(),
            out_spikes[0],
            out_spikes[1]
        );
    }

    // 5. Industrial Deployment via ModelDescriptor (Zero-Generic, Zero-Alloc SRAM)
    println!("\n5. Equivalent inference via industrial `ModelDescriptor` standard:");
    let l1_desc = LayerDescriptor::new_u32(4, 4, l1_synapses, lif_config, None);
    let l2_desc = LayerDescriptor::new_u32(4, 2, l2_synapses, lif_config, None);
    let layers = [l1_desc, l2_desc];
    let model = ModelDescriptor::new(&layers);

    let footprint = model.memory_footprint;
    println!(
        "   - Computed SRAM footprint: {} bytes (Strict zero heap)",
        footprint.total_sram_bytes
    );

    let mut sram = [0u8; 512];
    let mut ctx = model.init_context(&mut sram).expect("Valid SRAM context");
    let mut out_words = [0u32; 1];

    for (t, inp) in test_inputs.iter().enumerate() {
        model
            .step(&mut ctx, inp, &mut out_words)
            .expect("Step succeeded");
        let n0 = (out_words[0] & 1) != 0;
        let n1 = (out_words[0] & 2) != 0;
        println!(
            "   [ModelDescriptor #{}] Out Words: 0x{:08X} -> [Neuron 0: {}, Neuron 1: {}]",
            t, out_words[0], n0, n1
        );
    }

    println!(
        "\n✅ NIR -> snn_core AOT pipeline validated successfully (Zero dynamic allocations, 100% no_std)."
    );
}
