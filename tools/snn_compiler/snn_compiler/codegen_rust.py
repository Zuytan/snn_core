"""
snn_compiler.codegen_rust
Bare-metal Rust code generator (#![no_std], zero-allocation) for snn_core.
"""

from typing import Dict, List, Tuple, Any
from .ir import sanitize_ident, NirGraph
from .quantizer import float_to_fix32_bits, pade_exp_neg

def generate_rust_code(
    nodes: Dict[str, Any],
    edges: List[Tuple[str, str]],
    output_path: str,
    quantize_i8: bool = False,
    dt: float = 0.001,
    reset_mode: str = "subtract",
    use_arena: bool = False,
):
    """Generates complete Rust (.rs) file with Flash ROM structures and GeneratedNetwork."""
    lines = [
        "// ============================================================================",
        "// 🤖 Automatically generated by snn-core-compiler",
        "// ⚡ Target: Bare-metal no_std, 100% zero dynamic heap allocation during inference",
        "// ============================================================================",
        "",
        "#![allow(dead_code, unused_imports, unused_variables, non_upper_case_globals, unused_mut)]",
        "",
        "use snn_core::Fix32;",
        "use snn_core::traits::SpikingNetwork;",
        "use snn_core::domain::compact_population::CompactLifPopulation;",
        "use snn_core::domain::generic_static_neuron::{GenericStaticNeuronPopulation, HeterogeneousStaticNeuronPopulation};",
        "use snn_core::domain::models::lif::{LifConfig, LifDynamics, LifState, ResetMode};",
        "use snn_core::domain::models::cuba_lif::{CubaLifConfig, CubaLifDynamics, CubaLifState};",
        "use snn_core::domain::layers::{SpikingFeedforwardLayer, SpikingLayer, Conv2dSynapses};",
        "use snn_core::domain::rom_csr::{RomCsrSynapses, QuantizedRomCsrSynapses};",
        "use snn_core::domain::engine::{LayerDescriptor, ModelDescriptor, ExecutionContext, EngineError, MaxPool2dConfig};",
    ]

    if use_arena:
        lines.append("use snn_core::domain::arena::{ActivationArena, ArenaLifPopulation, ArenaFeedforwardLayer};")

    lines.append("")

    syn_nodes = {k: v for k, v in nodes.items() if v.get("type") in ("Linear", "Affine", "Conv1d", "Conv2d")}
    lif_nodes = {k: v for k, v in nodes.items() if v.get("type") in ("LIF", "CubaLIF", "IF")}
    pool_nodes = {k: v for k, v in nodes.items() if v.get("type") == "MaxPool2d"}

    # 1. Static ROM tables for synapses
    for name, data in syn_nodes.items():
        ident = sanitize_ident(name).upper()
        if data.get("type") == "Conv2d":
            in_ch = data.get("in_channels", 1)
            out_ch = data.get("out_channels", 1)
            kh = data.get("kernel_h", 1)
            kw = data.get("kernel_w", 1)
            sh = data.get("stride_h", 1)
            sw = data.get("stride_w", 1)
            pad_h = data.get("padding_h", 0)
            pad_w = data.get("padding_w", 0)
            in_h = data.get("in_h", 4)
            in_w = data.get("in_w", 4)
            weights = data.get("weights", [])
            in_f = in_ch * in_h * in_w
            out_h = (in_h + 2 * pad_h - kh) // sh + 1
            out_w = (in_w + 2 * pad_w - kw) // sw + 1
            out_f = out_ch * out_h * out_w

            lines.append(f"// --- 2D Convolutive Projection: {name} ({in_ch}x{in_h}x{in_w} -> {out_ch}x{out_h}x{out_w}) ---")
            lines.append(f"pub const {ident}_IN_FEATURES: usize = {in_f};")
            lines.append(f"pub const {ident}_OUT_FEATURES: usize = {out_f};")
            if weights:
                fix_bits = [f"Fix32::from_bits({float_to_fix32_bits(w)})" for w in weights]
                lines.append(f"pub static {ident}_KERNEL: [Fix32; {len(weights)}] = [\n    {', '.join(fix_bits)}\n];")
            else:
                lines.append(f"pub static {ident}_KERNEL: [Fix32; 1] = [Fix32::ZERO];")
            lines.append(f"pub static {ident}_SYNAPSES: Conv2dSynapses<'static, Fix32> = Conv2dSynapses::with_padding(")
            lines.append(f"    &{ident}_KERNEL, {in_ch}, {out_ch}, {kh}, {kw}, {sh}, {sw}, {pad_h}, {pad_w}, {in_h}, {in_w}")
            lines.append(");")
            if "bias" in data and data["bias"]:
                b_bits = [f"Fix32::from_bits({float_to_fix32_bits(b)})" for b in data["bias"]]
                lines.append(f"pub static {ident}_BIAS: [Fix32; {len(b_bits)}] = [\n    {', '.join(b_bits)}\n];")
            lines.append("")
            continue

        in_f = data["in_features"]
        out_f = data["out_features"]
        row_ptrs = data["row_ptrs"]
        targets = data["targets"]
        weights = data["weights"]

        lines.append(f"// --- Synaptic Projection: {name} ({in_f} -> {out_f}) ---")
        lines.append(f"pub const {ident}_IN_FEATURES: usize = {in_f};")
        lines.append(f"pub const {ident}_OUT_FEATURES: usize = {out_f};")
        lines.append(f"pub const {ident}_TOTAL_SYNAPSES: usize = {len(targets)};")
        lines.append(f"pub static {ident}_ROW_PTRS: [u16; {len(row_ptrs)}] = [{', '.join(map(str, row_ptrs))}];")

        if targets:
            lines.append(f"pub static {ident}_TARGETS: [u16; {len(targets)}] = [{', '.join(map(str, targets))}];")
        else:
            lines.append(f"pub static {ident}_TARGETS: [u16; 1] = [0];")

        if quantize_i8 and "weights_i8" in data:
            w_i8 = data["weights_i8"]
            scale_val = data["scale"]
            lines.append(f"pub static {ident}_WEIGHTS: [i8; {len(w_i8)}] = [{', '.join(map(str, w_i8))}];")
            lines.append(f"pub static {ident}_SYNAPSES: QuantizedRomCsrSynapses<'static, u16> = QuantizedRomCsrSynapses::new(")
            lines.append(f"    &{ident}_ROW_PTRS,")
            lines.append(f"    &{ident}_TARGETS,")
            lines.append(f"    &{ident}_WEIGHTS,")
            lines.append(f"    Fix32::from_bits({float_to_fix32_bits(scale_val)}),")
            lines.append(");")
        else:
            if weights:
                fix_bits = [f"Fix32::from_bits({float_to_fix32_bits(w)})" for w in weights]
                lines.append(f"pub static {ident}_WEIGHTS: [Fix32; {len(weights)}] = [\n    {', '.join(fix_bits)}\n];")
            else:
                lines.append(f"pub static {ident}_WEIGHTS: [Fix32; 1] = [Fix32::ZERO];")

            lines.append(f"pub static {ident}_SYNAPSES: RomCsrSynapses<'static, u16, Fix32> = RomCsrSynapses::new(")
            lines.append(f"    &{ident}_ROW_PTRS,")
            lines.append(f"    &{ident}_TARGETS,")
            lines.append(f"    &{ident}_WEIGHTS,")
            lines.append(");")

        if "bias" in data and data["bias"]:
            b_bits = [f"Fix32::from_bits({float_to_fix32_bits(b)})" for b in data["bias"]]
            lines.append(f"pub static {ident}_BIAS: [Fix32; {len(b_bits)}] = [\n    {', '.join(b_bits)}\n];")

        lines.append("")

    # 2. Neuron population configurations
    for name, data in lif_nodes.items():
        ident = sanitize_ident(name).upper()
        size = data.get("size", 1)
        tau = data.get("tau", 0.01)
        v_th = data.get("v_threshold", 1.0)
        v_reset = data.get("v_reset", 0.0)
        r = data.get("r", 1.0)
        is_cuba = data.get("type") == "CubaLIF"
        is_hetero = data.get("heterogeneous", False)

        lines.append(f"// --- Neuron Population: {name} ({size} neurons) ---")
        lines.append(f"pub const {ident}_SIZE: usize = {size};")

        alpha = pade_exp_neg(dt / tau) if tau > 0 else 0.0
        v_th_fix = float_to_fix32_bits(v_th)
        v_res_fix = float_to_fix32_bits(v_reset)
        alpha_fix = float_to_fix32_bits(alpha)
        r_fix = float_to_fix32_bits(r)
        rm_ident = "Subtract" if reset_mode == "subtract" else "Hard"

        if is_cuba:
            tau_syn = data.get("tau_syn", 0.005)
            alpha_syn = pade_exp_neg(dt / tau_syn) if tau_syn > 0 else 0.0
            alpha_syn_fix = float_to_fix32_bits(alpha_syn)
            lines.append(f"pub static {ident}_CONFIG: CubaLifConfig = CubaLifConfig::new(")
            lines.append(f"    Fix32::from_bits({v_th_fix}),")
            lines.append(f"    Fix32::from_bits({alpha_fix}),")
            lines.append(f"    Fix32::from_bits({alpha_syn_fix}),")
            lines.append(f"    Fix32::from_bits({v_res_fix}),")
            lines.append("    1,")
            lines.append(f").with_reset_mode(ResetMode::{rm_ident});")
        else:
            lines.append(f"pub static {ident}_CONFIG: LifConfig = LifConfig::new(")
            lines.append(f"    Fix32::from_bits({v_th_fix}),")
            lines.append(f"    Fix32::from_bits({alpha_fix}),")
            lines.append(f"    Fix32::from_bits({v_res_fix}),")
            lines.append("    1,")
            lines.append(f").with_reset_mode(ResetMode::{rm_ident});")

        lines.append("")

    # 3. Assembling the GeneratedNetwork
    feedforward_pairs = []
    for u, v in edges:
        if u in syn_nodes and v in lif_nodes:
            feedforward_pairs.append((u, v))

    # Unified Industrial ModelDescriptor API
    if feedforward_pairs:
        lines.append("// ============================================================================")
        lines.append("// 🚀 Unified Industrial ModelDescriptor API (Zero-Alloc, Flash ROM .rodata)")
        lines.append("// ============================================================================")
        layer_descs = []
        ir_graph = NirGraph(nodes, edges)
        liveness = ir_graph.compute_memory_liveness()
        allocated_offsets = liveness.get("offsets", {})
        lif_to_layer_idx = {l_name: idx for idx, (_, l_name) in enumerate(feedforward_pairs)}

        for idx, (s_name, l_name) in enumerate(feedforward_pairs):
            l_ident = sanitize_ident(l_name).upper()
            s_ident = sanitize_ident(s_name).upper()
            has_bias = "bias" in syn_nodes[s_name] and syn_nodes[s_name]["bias"]
            bias_ref = f"Some(&{s_ident}_BIAS)" if has_bias else "None"
            is_conv2d = syn_nodes[s_name].get("type") == "Conv2d"
            is_q = quantize_i8 and "weights_i8" in syn_nodes[s_name]
            if is_conv2d:
                constructor = "new_conv2d"
            elif is_q:
                constructor = "new_quantized_i8"
            else:
                constructor = "new"
            desc_code = f"    LayerDescriptor::{constructor}({s_ident}_IN_FEATURES, {l_ident}_SIZE, {s_ident}_SYNAPSES, {l_ident}_CONFIG, {bias_ref})"

            predecessors = [u for u, v in edges if v == s_name]
            if predecessors and predecessors[0] in lif_to_layer_idx:
                src_layer_idx = lif_to_layer_idx[predecessors[0]]
                if src_layer_idx != idx - 1:
                    desc_code += f"\n        .with_source_layer({src_layer_idx})"

            if l_name in allocated_offsets and allocated_offsets[l_name] > 0:
                word_offset = allocated_offsets[l_name] // 4
                desc_code += f"\n        .with_activation_offset({word_offset})"

            layer_descs.append(desc_code)

        num_layers = len(feedforward_pairs)
        lines.append(f"pub static MODEL_LAYERS: [LayerDescriptor<'static>; {num_layers}] = [\n" + ",\n".join(layer_descs) + "\n];")
        lines.append("pub static MODEL_DESC: ModelDescriptor<'static> = ModelDescriptor::new(&MODEL_LAYERS);")
        lines.append("")

    lines.append("pub struct GeneratedNetwork {")
    for idx, (s_name, l_name) in enumerate(feedforward_pairs):
        l_ident = sanitize_ident(l_name).upper()
        s_ident = sanitize_ident(s_name).upper()
        syn_type = "QuantizedRomCsrSynapses<'static, u16>" if (quantize_i8 and "weights_i8" in syn_nodes[s_name]) else "RomCsrSynapses<'static, u16, Fix32>"
        is_cuba = nodes[l_name].get("type") == "CubaLIF"
        is_hetero = nodes[l_name].get("heterogeneous", False)

        if is_hetero:
            pop_type = f"HeterogeneousStaticNeuronPopulation<'static, LifDynamics, {l_ident}_SIZE>"
        elif is_cuba:
            pop_type = f"GenericStaticNeuronPopulation<CubaLifDynamics, {l_ident}_SIZE>"
        else:
            pop_type = f"CompactLifPopulation<{l_ident}_SIZE>"

        lines.append(f"    pub layer_{idx + 1}: SpikingFeedforwardLayer<")
        lines.append(f"        {pop_type},")
        lines.append(f"        {syn_type},")
        lines.append(f"        {l_ident}_SIZE,")
        lines.append(f"        {{ {l_ident}_SIZE.div_ceil(32) }},")
        lines.append("    >,")

    last_l_ident = sanitize_ident(feedforward_pairs[-1][1]).upper() if feedforward_pairs else "OUTPUT"
    out_size = f"{last_l_ident}_SIZE" if feedforward_pairs else "0"
    lines.append(f"    pub output_spikes: [bool; {out_size}],")
    lines.append("}")
    lines.append("")

    # Constructor new()
    lines.append("impl GeneratedNetwork {")
    lines.append("    pub fn new() -> Self {")
    for idx, (s_name, l_name) in enumerate(feedforward_pairs):
        l_ident = sanitize_ident(l_name).upper()
        s_ident = sanitize_ident(s_name).upper()
        has_bias = "bias" in syn_nodes[s_name] and syn_nodes[s_name]["bias"]
        bias_code = f".with_bias(&{s_ident}_BIAS)" if has_bias else ""
        is_cuba = nodes[l_name].get("type") == "CubaLIF"
        is_hetero = nodes[l_name].get("heterogeneous", False)
        if is_hetero:
            lines.append(f"        let pop_{idx + 1} = HeterogeneousStaticNeuronPopulation::<LifDynamics, {l_ident}_SIZE>::new(&{l_ident}_CONFIGS, [LifState::default(); {l_ident}_SIZE]){bias_code};")
        elif is_cuba:
            lines.append(f"        let pop_{idx + 1} = GenericStaticNeuronPopulation::<CubaLifDynamics, {l_ident}_SIZE>::new({l_ident}_CONFIG, CubaLifState::default()){bias_code};")
        else:
            lines.append(f"        let pop_{idx + 1} = CompactLifPopulation::<{l_ident}_SIZE>::new({l_ident}_CONFIG){bias_code};")
        lines.append(f"        let layer_{idx + 1} = SpikingFeedforwardLayer::new(pop_{idx + 1}, {s_ident}_SYNAPSES);")
    lines.append("        Self {")
    for idx in range(len(feedforward_pairs)):
        lines.append(f"            layer_{idx + 1},")
    lines.append(f"            output_spikes: [false; {out_size}],")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    #[inline]")
    lines.append("    pub fn tick_inputs_words(&mut self, inputs: &[Fix32]) -> &[u32] {")
    if feedforward_pairs:
        if len(feedforward_pairs) == 1:
            lines.append("        self.layer_1.tick_inputs_words(inputs)")
        else:
            lines.append("        let mut current_words = self.layer_1.tick_inputs_words(inputs);")
            for idx in range(1, len(feedforward_pairs)):
                lines.append(f"        current_words = self.layer_{idx + 1}.tick_spikes_words(current_words);")
            lines.append("        current_words")
    lines.append("    }")
    lines.append("")
    lines.append("    #[inline]")
    lines.append("    pub fn tick_spikes_words(&mut self, prev_spikes_words: &[u32]) -> &[u32] {")
    if feedforward_pairs:
        if len(feedforward_pairs) == 1:
            lines.append("        self.layer_1.tick_spikes_words(prev_spikes_words)")
        else:
            lines.append("        let mut current_words = self.layer_1.tick_spikes_words(prev_spikes_words);")
            for idx in range(1, len(feedforward_pairs)):
                lines.append(f"        current_words = self.layer_{idx + 1}.tick_spikes_words(current_words);")
            lines.append("        current_words")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    lines.append("impl Default for GeneratedNetwork {")
    lines.append("    fn default() -> Self {")
    lines.append("        Self::new()")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    lines.append("impl SpikingNetwork for GeneratedNetwork {")
    lines.append("    fn tick(&mut self, inputs: &[Fix32]) -> &[bool] {")
    if feedforward_pairs:
        if len(feedforward_pairs) == 1:
            lines.append("        let _ = self.layer_1.tick_inputs_words(inputs);")
            last_idx = 1
        else:
            lines.append("        let mut current_words = self.layer_1.tick_inputs_words(inputs);")
            for idx in range(1, len(feedforward_pairs) - 1):
                lines.append(f"        current_words = self.layer_{idx + 1}.tick_spikes_words(current_words);")
            last_idx = len(feedforward_pairs)
            lines.append(f"        let _ = self.layer_{last_idx}.tick_spikes_words(current_words);")
        lines.append(f"        for i in 0..{last_l_ident}_SIZE {{")
        lines.append(f"            self.output_spikes[i] = self.layer_{last_idx}.get_spike(i);")
        lines.append("        }")
    lines.append("        &self.output_spikes")
    lines.append("    }")
    lines.append("")
    lines.append("    #[inline]")
    lines.append("    fn tick_spikes_words(&mut self, prev_spikes_words: &[u32]) -> &[u32] {")
    lines.append("        self.tick_spikes_words(prev_spikes_words)")
    lines.append("    }")
    lines.append("")
    lines.append("    fn reset(&mut self) {")
    for idx in range(len(feedforward_pairs)):
        lines.append(f"        self.layer_{idx + 1}.reset();")
    lines.append(f"        self.output_spikes = [false; {out_size}];")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    import os
    if os.path.dirname(output_path):
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
