"""
crystallize.py

Algebraic Crystallization Compiler (PyTorch / NumPy -> Rust u64).
Implements discretization guarantees from Section 7 (Lemma 7.1 and Theorem 7.2).
"""

from typing import List, Tuple, Union
import numpy as np


def pack_bits_to_u64(bits_array) -> int:
    """
    Packs a binary array of length 64 into an unsigned 64-bit integer (u64).
    Index 0 (present t) is the LSB (bit 0).
    Index 63 (past t-63) is the MSB (bit 63).
    """
    arr = np.asarray(bits_array, dtype=bool).flatten()
    if len(arr) != 64:
        raise ValueError(f"Mask length must be exactly 64 (got: {len(arr)})")
    
    val = 0
    for k in range(64):
        if arr[k]:
            val |= (1 << k)
    return val


def quantize_threshold(float_threshold: float) -> int:
    """
    Quantizes continuous threshold to optimal integer:
    theta = max(0, int(round(float_threshold)))
    """
    return max(0, int(round(float_threshold)))


def crystallize_layer(
    kernels: np.ndarray,      # Shape: [N_neurons, M_channels, 64]
    polarities: np.ndarray,   # Shape: [N_neurons, M_channels, 64]
    thresholds: np.ndarray,   # Shape: [N_neurons]
    threshold_margin: float = 0.5,
) -> Tuple[List[List[int]], List[List[int]], List[int]]:
    """
    Crystallizes continuous tensors into discrete integer tables (u64 and u32).
    
    Returns:
      (kernels_u64, polarities_u64, thresholds_u32)
    """
    n_neurons, m_channels, w = kernels.shape
    if w != 64:
        raise ValueError("Temporal dimension W must be 64.")
    
    # Binarize with threshold 0.5
    bin_k = (kernels >= 0.5)
    bin_p = (polarities >= 0.5)
    
    kernels_u64 = []
    polarities_u64 = []
    thresholds_u32 = []
    
    for n in range(n_neurons):
        k_list = [pack_bits_to_u64(bin_k[n, ch, :]) for ch in range(m_channels)]
        p_list = [pack_bits_to_u64(bin_p[n, ch, :]) for ch in range(m_channels)]
        th = quantize_threshold(float(thresholds[n]))
        
        kernels_u64.append(k_list)
        polarities_u64.append(p_list)
        thresholds_u32.append(th)
        
    return kernels_u64, polarities_u64, thresholds_u32


def crystallize_to_rust_constants(
    name_prefix: str,
    kernels_u64: List[List[int]],
    polarities_u64: List[List[int]],
    thresholds_u32: List[int],
) -> str:
    """
    Generates static Rust constants ready to be embedded into snn_core.
    """
    n_neurons = len(kernels_u64)
    m_channels = len(kernels_u64[0]) if n_neurons > 0 else 0
    prefix = name_prefix.upper()
    
    lines = [
        "// ============================================================================",
        f"// ⚡ Crystallized BPTN Model: {name_prefix} ({n_neurons} neurons, {m_channels} channels)",
        "// Automatically generated by tools/bptn_torch/crystallize.py",
        "// ============================================================================",
        f"pub const {prefix}_N_NEURONS: usize = {n_neurons};",
        f"pub const {prefix}_M_CHANNELS: usize = {m_channels};",
        "",
    ]
    
    # KERNELS
    lines.append(f"pub static {prefix}_KERNELS: [[u64; {m_channels}]; {n_neurons}] = [")
    for n in range(n_neurons):
        hex_row = ", ".join(f"0x{k:016X}_u64" for k in kernels_u64[n])
        lines.append(f"    [{hex_row}],")
    lines.append("];\n")
    
    # POLARITIES
    lines.append(f"pub static {prefix}_POLARITIES: [[u64; {m_channels}]; {n_neurons}] = [")
    for n in range(n_neurons):
        hex_row = ", ".join(f"0x{p:016X}_u64" for p in polarities_u64[n])
        lines.append(f"    [{hex_row}],")
    lines.append("];\n")
    
    # THRESHOLDS
    th_row = ", ".join(str(th) for th in thresholds_u32)
    lines.append(f"pub static {prefix}_THRESHOLDS: [u32; {n_neurons}] = [{th_row}];\n")
    
    # INSTANTIATION HELPER
    lines.append("/// Instantiates the crystallized feedforward layer directly in Flash ROM.")
    lines.append("#[inline(always)]")
    lines.append(f"pub const fn create_{name_prefix.lower()}_layer() -> snn_core::BptnFeedforwardLayer<{n_neurons}, {m_channels}> {{")
    lines.append(f"    let mut neurons = [snn_core::CompactBptnNeuron::<{m_channels}>::new([0; {m_channels}], [0; {m_channels}], 0); {n_neurons}];")
    lines.append("    let mut i = 0;")
    lines.append(f"    while i < {n_neurons} {{")
    lines.append("        neurons[i] = snn_core::CompactBptnNeuron::new(")
    lines.append(f"            {prefix}_KERNELS[i],")
    lines.append(f"            {prefix}_POLARITIES[i],")
    lines.append(f"            {prefix}_THRESHOLDS[i],")
    lines.append("        );")
    lines.append("        i += 1;")
    lines.append("    }")
    lines.append("    snn_core::BptnFeedforwardLayer::new(neurons)")
    lines.append("}")
    
    return "\n".join(lines)


def crystallize_to_rust_struct(
    name_prefix: str,
    kernels: np.ndarray,
    polarities: np.ndarray,
    thresholds: np.ndarray,
) -> str:
    """All-in-one shortcut to directly export continuous tensors into Rust."""
    k_u64, p_u64, th_u32 = crystallize_layer(kernels, polarities, thresholds)
    return crystallize_to_rust_constants(name_prefix, k_u64, p_u64, th_u32)


def export_rust_header(filename: str, code: str):
    """Writes generated code to a .rs file."""
    with open(filename, "w", encoding="utf-8") as f:
        f.write(code)
    print(f"✅ Crystallized Rust code written to: {filename}")
