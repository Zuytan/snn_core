//! 🦀 Pure Rust AOT Compiler for Neuromorphic Intermediate Representation (NIR) models
//!
//! Converts a NIR graph (JSON) into ultra-optimized static Rust code (`no_std`, zero heap allocation)
//! directly usable in the `build.rs` of an embedded firmware or via the `snn_core_codegen` CLI.

use serde::Deserialize;
use std::collections::{HashMap, HashSet, VecDeque};
use std::error::Error;
use std::fmt::Write as FmtWrite;
use std::fs;
use std::path::Path;

/// Padé (2,2) approximant for exp(-x), guaranteeing relative error < 0.005%.
pub fn pade_exp_neg(x: f64) -> f64 {
    if x <= 0.0 {
        return 1.0;
    }
    if x >= 10.0 {
        return 0.0;
    }
    let num = (12.0 - 6.0 * x) + (x * x);
    let den = (12.0 + 6.0 * x) + (x * x);
    if num <= 0.0 { 0.0 } else { num / den }
}

/// Converts a float f64 into a Q16.16 binary integer value (Fix32).
pub fn float_to_fix32_bits(val: f64) -> i32 {
    let scaled = (val * 65536.0).round();
    if scaled > (i32::MAX as f64) {
        i32::MAX
    } else if scaled < (i32::MIN as f64) {
        i32::MIN
    } else {
        scaled as i32
    }
}

#[derive(Debug, Deserialize)]
pub struct NirGraph {
    pub nodes: HashMap<String, NirNodeData>,
    pub edges: Vec<(String, String)>,
}

#[derive(Debug, Deserialize)]
pub struct NirNodeData {
    #[serde(rename = "type")]
    pub node_type: String,
    pub in_features: Option<usize>,
    pub out_features: Option<usize>,
    pub size: Option<usize>,
    pub weight: Option<serde_json::Value>,
    pub bias: Option<serde_json::Value>,
    pub tau: Option<serde_json::Value>,
    pub v_threshold: Option<serde_json::Value>,
    pub v_reset: Option<serde_json::Value>,
    pub r: Option<serde_json::Value>,
    pub dt: Option<f64>,
    pub reset_mode: Option<String>,
}

fn extract_floats(val: &serde_json::Value) -> Vec<f64> {
    match val {
        serde_json::Value::Number(n) => vec![n.as_f64().unwrap_or(0.0)],
        serde_json::Value::Array(arr) => {
            let mut res = Vec::new();
            for item in arr {
                res.extend(extract_floats(item));
            }
            res
        }
        _ => Vec::new(),
    }
}

fn sanitize_ident(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect()
}

/// Performs topological sort of the NIR DAG.
pub fn topological_sort(
    nodes: &HashMap<String, NirNodeData>,
    edges: &[(String, String)],
) -> Vec<String> {
    let mut in_degree: HashMap<String, usize> = HashMap::new();
    let mut adj: HashMap<String, Vec<String>> = HashMap::new();

    for k in nodes.keys() {
        in_degree.insert(k.clone(), 0);
        adj.insert(k.clone(), Vec::new());
    }

    for (u, v) in edges {
        if nodes.contains_key(u) && nodes.contains_key(v) {
            adj.get_mut(u).unwrap().push(v.clone());
            *in_degree.get_mut(v).unwrap() += 1;
        }
    }

    let mut queue = VecDeque::new();
    for (k, deg) in &in_degree {
        if *deg == 0 {
            queue.push_back(k.clone());
        }
    }

    let mut sorted = Vec::new();
    while let Some(u) = queue.pop_front() {
        sorted.push(u.clone());
        if let Some(neighbors) = adj.get(&u) {
            for v in neighbors {
                let deg = in_degree.get_mut(v).unwrap();
                *deg -= 1;
                if *deg == 0 {
                    queue.push_back(v.clone());
                }
            }
        }
    }

    // If some nodes are not in sorted (disconnected graph), append them
    let seen: HashSet<String> = sorted.iter().cloned().collect();
    for k in nodes.keys() {
        if !seen.contains(k) {
            sorted.push(k.clone());
        }
    }

    sorted
}

/// Compiles a NIR JSON model into static `no_std` Rust code.
pub fn compile_nir_json(json_str: &str, quantize_i8: bool) -> Result<String, Box<dyn Error>> {
    let graph: NirGraph = serde_json::from_str(json_str)?;
    let mut out = String::new();

    writeln!(
        out,
        "// ==========================================================================="
    )?;
    writeln!(
        out,
        "// 🦀 Rust Code Auto-Generated by snn_core_codegen (AOT NIR Compiler)"
    )?;
    writeln!(
        out,
        "// Ultra-optimized neuromorphic model (#![no_std], zero allocation in inference)"
    )?;
    writeln!(
        out,
        "// ===========================================================================\n"
    )?;

    writeln!(
        out,
        "#![allow(dead_code, unused_imports, non_upper_case_globals)]"
    )?;
    writeln!(out, "use snn_core::domain::bitset::SpikeBitset;")?;
    writeln!(
        out,
        "use snn_core::domain::compact_population::CompactLifPopulation;"
    )?;
    writeln!(
        out,
        "use snn_core::domain::generic_static_neuron::{{GenericStaticNeuronPopulation, HeterogeneousStaticNeuronPopulation}};"
    )?;
    writeln!(
        out,
        "use snn_core::domain::layers::{{SpikingFeedforwardLayer, QuantizedFeedforwardLayer, SpikingLayer}};"
    )?;
    writeln!(
        out,
        "use snn_core::domain::models::lif::{{LifConfig, LifDynamics, LifState, ResetMode}};"
    )?;
    writeln!(out, "use snn_core::domain::numeric::Fix32;")?;
    writeln!(
        out,
        "use snn_core::domain::rom_csr::{{RomCsrSynapses, QuantizedRomCsrSynapses}};"
    )?;
    writeln!(out, "use snn_core::traits::SpikingNetwork;\n")?;

    let default_dt = 0.001;
    let sorted_nodes = topological_sort(&graph.nodes, &graph.edges);

    // 1. Emission of synapse structures and populations
    for node_name in &sorted_nodes {
        let node_data = &graph.nodes[node_name];
        let ident = sanitize_ident(node_name).to_uppercase();

        match node_data.node_type.as_str() {
            "Linear" | "Affine" => {
                let weights = node_data
                    .weight
                    .as_ref()
                    .map(extract_floats)
                    .unwrap_or_default();
                let in_feat = node_data.in_features.unwrap_or(1);
                let out_feat = node_data
                    .out_features
                    .unwrap_or(weights.len() / in_feat.max(1));

                // Dense to CSR conversion
                let mut row_ptrs = vec![0u16];
                let mut targets = Vec::new();
                let mut csr_weights = Vec::new();

                for i in 0..in_feat {
                    let mut count = 0u16;
                    for j in 0..out_feat {
                        let idx = i * out_feat + j;
                        if idx < weights.len() {
                            let w = weights[idx];
                            if w.abs() > 1e-6 {
                                targets.push(j as u16);
                                csr_weights.push(w);
                                count += 1;
                            }
                        }
                    }
                    row_ptrs.push(row_ptrs.last().unwrap() + count);
                }

                writeln!(out, "// --- Flash ROM Synapses: {} ---", node_name)?;
                writeln!(
                    out,
                    "pub static {}_ROW_PTRS: [u16; {}] = {:?};",
                    ident,
                    row_ptrs.len(),
                    row_ptrs
                )?;
                writeln!(
                    out,
                    "pub static {}_TARGETS: [u16; {}] = {:?};",
                    ident,
                    targets.len(),
                    targets
                )?;

                if quantize_i8 {
                    let max_abs = csr_weights.iter().map(|w| w.abs()).fold(1e-6, f64::max);
                    let scale = max_abs / 127.0;
                    let quantized: Vec<i8> = csr_weights
                        .iter()
                        .map(|w| (w / scale).round().clamp(-128.0, 127.0) as i8)
                        .collect();

                    writeln!(
                        out,
                        "pub static {}_WEIGHTS_I8: [i8; {}] = {:?};",
                        ident,
                        quantized.len(),
                        quantized
                    )?;
                    writeln!(
                        out,
                        "pub const {}_SCALE: Fix32 = Fix32::from_bits({});",
                        ident,
                        float_to_fix32_bits(scale)
                    )?;
                    writeln!(
                        out,
                        "pub static {}_SYNAPSES: QuantizedRomCsrSynapses<'static, u16> = QuantizedRomCsrSynapses::new(",
                        ident
                    )?;
                    writeln!(
                        out,
                        "    &{}_ROW_PTRS, &{}_TARGETS, &{}_WEIGHTS_I8, {}_SCALE,",
                        ident, ident, ident, ident
                    )?;
                    writeln!(out, ");\n")?;
                } else {
                    let fix_weights: Vec<i32> = csr_weights
                        .iter()
                        .map(|&w| float_to_fix32_bits(w))
                        .collect();
                    writeln!(
                        out,
                        "pub static {}_WEIGHTS: [Fix32; {}] = [",
                        ident,
                        fix_weights.len()
                    )?;
                    for b in fix_weights {
                        writeln!(out, "    Fix32::from_bits({}),", b)?;
                    }
                    writeln!(out, "];")?;
                    writeln!(
                        out,
                        "pub static {}_SYNAPSES: RomCsrSynapses<'static, u16, Fix32> = RomCsrSynapses::new(",
                        ident
                    )?;
                    writeln!(
                        out,
                        "    &{}_ROW_PTRS, &{}_TARGETS, &{}_WEIGHTS,",
                        ident, ident, ident
                    )?;
                    writeln!(out, ");\n")?;
                }
            }
            "LIF" | "IF" => {
                let size = node_data.size.unwrap_or(1);
                let tau_vals = node_data
                    .tau
                    .as_ref()
                    .map(extract_floats)
                    .unwrap_or_else(|| vec![0.01]);
                let v_th_vals = node_data
                    .v_threshold
                    .as_ref()
                    .map(extract_floats)
                    .unwrap_or_else(|| vec![1.0]);
                let v_reset_vals = node_data
                    .v_reset
                    .as_ref()
                    .map(extract_floats)
                    .unwrap_or_else(|| vec![0.0]);
                let r_vals = node_data
                    .r
                    .as_ref()
                    .map(extract_floats)
                    .unwrap_or_else(|| vec![1.0]);
                let dt = node_data.dt.unwrap_or(default_dt);
                let reset_mode = node_data.reset_mode.as_deref().unwrap_or("subtract");

                writeln!(
                    out,
                    "// --- Neuron Population: {} ({} neurons) ---",
                    node_name, size
                )?;
                writeln!(out, "pub const {}_SIZE: usize = {};", ident, size)?;

                let is_hetero = tau_vals.len() > 1 || v_th_vals.len() > 1 || r_vals.len() > 1;
                if is_hetero {
                    writeln!(
                        out,
                        "pub static {}_CONFIGS: [LifConfig; {}_SIZE] = [",
                        ident, ident
                    )?;
                    for i in 0..size {
                        let t_i = tau_vals[i % tau_vals.len()];
                        let mut v_i = v_th_vals[i % v_th_vals.len()];
                        let mut vr_i = v_reset_vals[i % v_reset_vals.len()];
                        let r_i = r_vals[i % r_vals.len()];
                        if r_i != 0.0 && r_i != 1.0 {
                            v_i /= r_i;
                            vr_i /= r_i;
                        }
                        let d_i = if node_data.node_type != "IF" && t_i > 0.0 {
                            pade_exp_neg(dt / t_i)
                        } else {
                            1.0
                        };
                        writeln!(
                            out,
                            "    LifConfig::new(Fix32::from_bits({}), Fix32::from_bits({}), Fix32::from_bits({}), 1).with_reset_mode(ResetMode::{}),",
                            float_to_fix32_bits(v_i),
                            float_to_fix32_bits(d_i),
                            float_to_fix32_bits(vr_i),
                            if reset_mode.eq_ignore_ascii_case("hard") {
                                "Hard"
                            } else {
                                "Subtract"
                            }
                        )?;
                    }
                    writeln!(out, "];\n")?;
                } else {
                    let mut v_val = v_th_vals[0];
                    let mut vr_val = v_reset_vals[0];
                    let r_val = r_vals[0];
                    if r_val != 0.0 && r_val != 1.0 {
                        v_val /= r_val;
                        vr_val /= r_val;
                    }
                    let decay = if node_data.node_type != "IF" && tau_vals[0] > 0.0 {
                        pade_exp_neg(dt / tau_vals[0])
                    } else {
                        1.0
                    };
                    writeln!(
                        out,
                        "pub const {}_CONFIG: LifConfig = LifConfig::new(",
                        ident
                    )?;
                    writeln!(
                        out,
                        "    Fix32::from_bits({}), Fix32::from_bits({}), Fix32::from_bits({}), 1",
                        float_to_fix32_bits(v_val),
                        float_to_fix32_bits(decay),
                        float_to_fix32_bits(vr_val)
                    )?;
                    writeln!(
                        out,
                        ").with_reset_mode(ResetMode::{});\n",
                        if reset_mode.eq_ignore_ascii_case("hard") {
                            "Hard"
                        } else {
                            "Subtract"
                        }
                    )?;
                }
            }
            _ => {}
        }
    }

    // 2. Identification of ordered feedforward layer pairs
    let mut feedforward_pairs = Vec::new();
    let lif_nodes: HashSet<&str> = graph
        .nodes
        .iter()
        .filter(|(_, d)| matches!(d.node_type.as_str(), "LIF" | "IF" | "CubaLIF"))
        .map(|(k, _)| k.as_str())
        .collect();
    let syn_nodes: HashSet<&str> = graph
        .nodes
        .iter()
        .filter(|(_, d)| matches!(d.node_type.as_str(), "Linear" | "Affine"))
        .map(|(k, _)| k.as_str())
        .collect();

    for (u, v) in &graph.edges {
        if syn_nodes.contains(u.as_str()) && lif_nodes.contains(v.as_str()) {
            feedforward_pairs.push((u.clone(), v.clone()));
        }
    }

    // 3. Definition of GeneratedNetwork struct
    writeln!(out, "// --- Compiled Network Structure ---")?;
    writeln!(out, "#[derive(Clone, Copy, Debug)]")?;
    writeln!(out, "pub struct GeneratedNetwork {{")?;
    for (idx, (_s_name, l_name)) in feedforward_pairs.iter().enumerate() {
        let l_ident = sanitize_ident(l_name).to_uppercase();
        let is_hetero = graph.nodes[l_name]
            .tau
            .as_ref()
            .map(extract_floats)
            .is_some_and(|v| v.len() > 1);
        let pop_type = if is_hetero {
            format!(
                "HeterogeneousStaticNeuronPopulation<'static, LifDynamics, {}_SIZE>",
                l_ident
            )
        } else {
            format!("CompactLifPopulation<{}_SIZE>", l_ident)
        };

        if quantize_i8 {
            writeln!(out, "    pub layer_{}: QuantizedFeedforwardLayer<", idx + 1)?;
            writeln!(
                out,
                "        {}, u16, {}_SIZE, {{ ({}_SIZE + 31) / 32 }}",
                pop_type, l_ident, l_ident
            )?;
            writeln!(out, "    >,")?;
        } else {
            writeln!(out, "    pub layer_{}: SpikingFeedforwardLayer<", idx + 1)?;
            writeln!(
                out,
                "        {}, RomCsrSynapses<'static, u16, Fix32>, {}_SIZE, {{ ({}_SIZE + 31) / 32 }}",
                pop_type, l_ident, l_ident
            )?;
            writeln!(out, "    >,")?;
        }
    }
    let last_l_ident = feedforward_pairs
        .last()
        .map(|(_, l)| sanitize_ident(l).to_uppercase())
        .unwrap_or_else(|| "0".to_string());
    writeln!(out, "    pub output_spikes: [bool; {}_SIZE],", last_l_ident)?;
    writeln!(out, "}}\n")?;

    // 4. new() constructor and inference methods
    writeln!(out, "impl GeneratedNetwork {{")?;
    writeln!(out, "    pub fn new() -> Self {{")?;
    for (idx, (s_name, l_name)) in feedforward_pairs.iter().enumerate() {
        let l_ident = sanitize_ident(l_name).to_uppercase();
        let s_ident = sanitize_ident(s_name).to_uppercase();
        let is_hetero = graph.nodes[l_name]
            .tau
            .as_ref()
            .map(extract_floats)
            .is_some_and(|v| v.len() > 1);

        if is_hetero {
            writeln!(
                out,
                "        let pop_{} = HeterogeneousStaticNeuronPopulation::<LifDynamics, {}_SIZE>::new(&{}_CONFIGS, [LifState::default(); {}_SIZE]);",
                idx + 1,
                l_ident,
                l_ident,
                l_ident
            )?;
        } else {
            writeln!(
                out,
                "        let pop_{} = CompactLifPopulation::<{}_SIZE>::new({}_CONFIG);",
                idx + 1,
                l_ident,
                l_ident
            )?;
        }

        if quantize_i8 {
            writeln!(
                out,
                "        let layer_{} = QuantizedFeedforwardLayer::new(pop_{}, {}_SYNAPSES);",
                idx + 1,
                idx + 1,
                s_ident
            )?;
        } else {
            writeln!(
                out,
                "        let layer_{} = SpikingFeedforwardLayer::new(pop_{}, {}_SYNAPSES);",
                idx + 1,
                idx + 1,
                s_ident
            )?;
        }
    }
    writeln!(out, "        Self {{")?;
    for idx in 0..feedforward_pairs.len() {
        writeln!(out, "            layer_{},", idx + 1)?;
    }
    writeln!(
        out,
        "            output_spikes: [false; {}_SIZE],",
        last_l_ident
    )?;
    writeln!(out, "        }}")?;
    writeln!(out, "    }}")?;

    writeln!(out, "\n    #[inline]")?;
    writeln!(
        out,
        "    pub fn tick_spikes_words(&mut self, prev_spikes_words: &[u32]) -> &[u32] {{"
    )?;
    if !feedforward_pairs.is_empty() {
        if feedforward_pairs.len() == 1 {
            writeln!(
                out,
                "        self.layer_1.tick_spikes_words(prev_spikes_words)"
            )?;
        } else {
            writeln!(
                out,
                "        let mut cur = self.layer_1.tick_spikes_words(prev_spikes_words);"
            )?;
            for idx in 1..feedforward_pairs.len() {
                writeln!(
                    out,
                    "        cur = self.layer_{}.tick_spikes_words(cur);",
                    idx + 1
                )?;
            }
            writeln!(out, "        cur")?;
        }
    } else {
        writeln!(out, "        &[]")?;
    }
    writeln!(out, "    }}")?;
    writeln!(out, "}}\n")?;

    // Default and SpikingNetwork
    writeln!(out, "impl Default for GeneratedNetwork {{")?;
    writeln!(out, "    fn default() -> Self {{ Self::new() }}")?;
    writeln!(out, "}}\n")?;

    writeln!(out, "impl SpikingNetwork<Fix32> for GeneratedNetwork {{")?;
    writeln!(
        out,
        "    fn tick(&mut self, _inputs: &[Fix32]) -> &[bool] {{"
    )?;
    writeln!(out, "        &self.output_spikes")?;
    writeln!(out, "    }}")?;
    writeln!(out, "    #[inline]")?;
    writeln!(
        out,
        "    fn tick_spikes_words(&mut self, prev_spikes_words: &[u32]) -> &[u32] {{"
    )?;
    writeln!(out, "        self.tick_spikes_words(prev_spikes_words)")?;
    writeln!(out, "    }}")?;
    writeln!(out, "    fn reset(&mut self) {{")?;
    for idx in 0..feedforward_pairs.len() {
        writeln!(out, "        self.layer_{}.reset();", idx + 1)?;
    }
    writeln!(out, "    }}")?;
    writeln!(out, "}}\n")?;

    Ok(out)
}

/// Compiles a NIR JSON file into a Rust firmware file.
pub fn compile_nir_file<P: AsRef<Path>>(
    input_path: P,
    output_path: P,
    quantize_i8: bool,
) -> Result<(), Box<dyn Error>> {
    let content = fs::read_to_string(input_path)?;
    let generated = compile_nir_json(&content, quantize_i8)?;
    fs::write(output_path, generated)?;
    Ok(())
}
